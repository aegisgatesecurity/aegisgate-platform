# Character Normalizer (MUST match pkg/ml/normalizer.go)
# =========================================================================
class CharNormalizer:
    """Character-level normalizer matching the Go implementation exactly.
    
    Go normalizer rules (from pkg/ml/normalizer.go):
    1. Convert to lowercase
    2. Strip leading/trailing whitespace
    3. Collapse multiple whitespace to single space
    4. Truncate to 128 characters
    5. Map printable ASCII [32-126] to their code point
    6. Map everything else to UNK (1)
    7. Pad to 128 with PAD (0)
    """

    def normalize(self, text: str) -> str:
        """Normalize text to match Go normalizer."""
        # Lowercase
        text = text.lower()
        # Strip
        text = text.strip()
        # Collapse whitespace
        result = []
        prev_space = False
        for ch in text:
            if ch in (' ', '\t', '\n', '\r'):
                if not prev_space:
                    result.append(' ')
                    prev_space = True
            else:
                result.append(ch)
                prev_space = False
        text = ''.join(result)
        # Truncate
        if len(text) > MAX_SEQ_LEN:
            text = text[:MAX_SEQ_LEN]
        return text

    def encode(self, text: str) -> list:
        """Encode normalized text to fixed-length integer array.
        
        Matches Go CharNormalizer.Encode() exactly:
        - Printable ASCII [32-126] → code point
        - Non-printable/non-ASCII → UNK_ID (1)
        - Padding → PAD_ID (0)
        """
        normalized = self.normalize(text)
        result = [PAD_ID] * MAX_SEQ_LEN
        
        for i, ch in enumerate(normalized):
            if i >= MAX_SEQ_LEN:
                break
            code = ord(ch)
            if 32 <= code <= 126:
                result[i] = code
            elif code < 128:
                result[i] = UNK_ID
            else:
                result[i] = UNK_ID
        
        return result


