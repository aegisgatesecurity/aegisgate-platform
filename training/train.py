class FocalLoss(nn.Module):
    """Focal loss for handling class imbalance.
    
    With alpha=0.25 and gamma=2.0, this reduces loss contribution from
    easy (well-classified) examples and focuses on hard examples.
    This helps achieve 0% FPR by heavily penalizing false positives.
    """

    def __init__(self, alpha: float = 0.25, gamma: float = 2.0):
        super().__init__()
        self.alpha = alpha
        self.gamma = gamma

    def forward(self, predictions: torch.Tensor, targets: torch.Tensor) -> torch.Tensor:
        bce = F.binary_cross_entropy(predictions, targets, reduction='none')
        p_t = targets * predictions + (1 - targets) * (1 - predictions)
        focal_weight = (1 - p_t) ** self.gamma
        alpha_weight = targets * self.alpha + (1 - targets) * (1 - self.alpha)
        loss = alpha_weight * focal_weight * bce
        return loss.mean()


def train_epoch(model: ThreatCNNBiLSTM, dataloader: DataLoader,
                optimizer: optim.Optimizer, criterion: nn.Module,
                device: torch.device) -> dict:
    """Train for one epoch."""
    model.train()
    total_loss = 0
    correct = 0
    total = 0
    tp = 0  # True positives (adversarial correctly detected)
    fp = 0  # False positives (benign incorrectly flagged)
    fn = 0  # False negatives (adversarial missed)
    tn = 0  # True negatives (benign correctly passed)

    for batch in dataloader:
        input_ids = batch["input_ids"].to(device)
        labels = batch["label"].to(device)

        optimizer.zero_grad()
        outputs = model(input_ids).squeeze(-1)

        loss = criterion(outputs, labels)
        loss.backward()

        # Gradient clipping for stability
        torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)

        optimizer.step()

        # Metrics
        total_loss += loss.item() * input_ids.size(0)
        predictions = (outputs >= 0.5).float()
        correct += (predictions == labels).sum().item()
        total += input_ids.size(0)

        # Confusion matrix
        tp += ((predictions == 1) & (labels == 1)).sum().item()
        fp += ((predictions == 1) & (labels == 0)).sum().item()
        fn += ((predictions == 0) & (labels == 1)).sum().item()
        tn += ((predictions == 0) & (labels == 0)).sum().item()

    accuracy = correct / total if total > 0 else 0
    fpr = fp / (fp + tn) if (fp + tn) > 0 else 0
    fnr = fn / (fn + tp) if (fn + tp) > 0 else 0
    precision = tp / (tp + fp) if (tp + fp) > 0 else 0
    recall = tp / (tp + fn) if (tp + fn) > 0 else 0
    f1 = 2 * precision * recall / (precision + recall) if (precision + recall) > 0 else 0

    return {
        "loss": total_loss / total,
        "accuracy": accuracy,
        "fpr": fpr,
        "fnr": fnr,
        "precision": precision,
        "recall": recall,
        "f1": f1,
        "tp": tp, "fp": fp, "fn": fn, "tn": tn,
    }


@torch.no_grad()
def evaluate(model: ThreatCNNBiLSTM, dataloader: DataLoader,
             criterion: nn.Module, device: torch.device) -> dict:
    """Evaluate the model."""
    model.eval()
    total_loss = 0
    correct = 0
    total = 0
    tp = fp = fn = tn = 0

    for batch in dataloader:
        input_ids = batch["input_ids"].to(device)
        labels = batch["label"].to(device)

        outputs = model(input_ids).squeeze(-1)
        loss = criterion(outputs, labels)

        total_loss += loss.item() * input_ids.size(0)
        predictions = (outputs >= 0.5).float()
        correct += (predictions == labels).sum().item()
        total += input_ids.size(0)

        tp += ((predictions == 1) & (labels == 1)).sum().item()
        fp += ((predictions == 1) & (labels == 0)).sum().item()
        fn += ((predictions == 0) & (labels == 1)).sum().item()
        tn += ((predictions == 0) & (labels == 0)).sum().item()

    accuracy = correct / total if total > 0 else 0
    fpr = fp / (fp + tn) if (fp + tn) > 0 else 0
    fnr = fn / (fn + tp) if (fn + tp) > 0 else 0
    precision = tp / (tp + fp) if (tp + fp) > 0 else 0
    recall = tp / (tp + fn) if (tp + fn) > 0 else 0
    f1 = 2 * precision * recall / (precision + recall) if (precision + recall) > 0 else 0

    return {
        "loss": total_loss / total,
        "accuracy": accuracy,
        "fpr": fpr,
        "fnr": fnr,
        "precision": precision,
        "recall": recall,
        "f1": f1,
        "tp": tp, "fp": fp, "fn": fn, "tn": tn,
    }


def train_model(
    model: ThreatCNNBiLSTM,
    train_dataset: ThreatDataset,
    val_dataset: ThreatDataset,
    test_dataset: ThreatDataset,
    epochs: int = DEFAULT_EPOCHS,
    batch_size: int = DEFAULT_BATCH_SIZE,
    learning_rate: float = DEFAULT_LEARNING_RATE,
    device: str = "auto",
    output_dir: str = "training/checkpoints",
):
    """Train the ThreatCNNBiLSTM model.
    
    Uses cosine annealing learning rate schedule and focal loss
    for class imbalance. Targets 0% FPR on benign traffic.
    """
    # Device selection
    if device == "auto":
        device = "cuda" if torch.cuda.is_available() else "cpu"
    device = torch.device(device)
    print(f"Training on device: {device}")

    # Data loaders
    train_loader = DataLoader(
        train_dataset, batch_size=batch_size, shuffle=True,
        num_workers=0, pin_memory=device.type == "cuda"
    )
    val_loader = DataLoader(
        val_dataset, batch_size=batch_size, shuffle=False,
        num_workers=0, pin_memory=device.type == "cuda"
    )
    test_loader = DataLoader(
        test_dataset, batch_size=batch_size, shuffle=False,
        num_workers=0, pin_memory=device.type == "cuda"
    )

    # Optimizer and scheduler
    optimizer = optim.AdamW(model.parameters(), lr=learning_rate, weight_decay=0.01)
    scheduler = optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=epochs, eta_min=1e-6)

    # Loss: focal loss for class imbalance (alpha=0.25 for adversarial minority)
    criterion = FocalLoss(alpha=0.25, gamma=2.0)

    # Move model to device
    model = model.to(device)

    # Output directory
    output_path = Path(output_dir)
    output_path.mkdir(parents=True, exist_ok=True)

    # Training loop
    best_val_f1 = 0
    best_epoch = 0
    best_model_state = None
    zero_fpr_model_state = None  # Model with 0% FPR on validation

    print(f"\n{'='*80}")
    print(f"AegisGate ThreatCNN-BiLSTM Training")
    print(f"{'='*80}")
    print(f"Model parameters: {model.count_parameters():,}")
    print(f"Train examples: {len(train_dataset)}")
    print(f"Val examples: {len(val_dataset)}")
    print(f"Test examples: {len(test_dataset)}")
    print(f"Epochs: {epochs}, Batch size: {batch_size}, LR: {learning_rate}")
    print(f"{'='*80}\n")

    start_time = time.time()

    for epoch in range(1, epochs + 1):
        epoch_start = time.time()

        # Train
        train_metrics = train_epoch(model, train_loader, optimizer, criterion, device)

        # Validate
        val_metrics = evaluate(model, val_loader, criterion, device)

        # Update learning rate
        scheduler.step()

        epoch_time = time.time() - epoch_start

        # Print progress
        print(f"Epoch {epoch:3d}/{epochs} | "
              f"Train Loss: {train_metrics['loss']:.4f} Acc: {train_metrics['accuracy']:.4f} | "
              f"Val Loss: {val_metrics['loss']:.4f} Acc: {val_metrics['accuracy']:.4f} | "
              f"Val FPR: {val_metrics['fpr']:.4f} FNR: {val_metrics['fnr']:.4f} "
              f"F1: {val_metrics['f1']:.4f} | "
              f"Time: {epoch_time:.1f}s")

        # Save best model by F1 score
        if val_metrics['f1'] > best_val_f1:
            best_val_f1 = val_metrics['f1']
            best_epoch = epoch
            best_model_state = {k: v.cpu().clone() for k, v in model.state_dict().items()}
            torch.save(best_model_state, output_path / "best_model.pt")
            print(f"  ✅ New best model (F1: {best_val_f1:.4f})")

        # Save model with zero FPR (our hard requirement)
        if val_metrics['fpr'] == 0.0 and val_metrics['f1'] > 0.5:
            zero_fpr_model_state = {k: v.cpu().clone() for k, v in model.state_dict().items()}
            torch.save(zero_fpr_model_state, output_path / "zero_fpr_model.pt")
            print(f"  🎯 Zero FPR model saved (F1: {val_metrics['f1']:.4f})")

    total_time = time.time() - start_time

    # Load best model for final evaluation
    print(f"\n{'='*80}")
    print(f"Training complete in {total_time:.1f}s")
    print(f"Best validation F1: {best_val_f1:.4f} at epoch {best_epoch}")

    # Evaluate best model on test set
    if best_model_state is not None:
        model.load_state_dict(best_model_state)
        model = model.to(device)

    test_metrics = evaluate(model, test_loader, criterion, device)

    print(f"\n{'='*80}")
    print(f"Test Results (Best F1 Model)")
    print(f"{'='*80}")
    print(f"  Loss:      {test_metrics['loss']:.4f}")
    print(f"  Accuracy:  {test_metrics['accuracy']:.4f}")
    print(f"  Precision: {test_metrics['precision']:.4f}")
    print(f"  Recall:    {test_metrics['recall']:.4f}")
    print(f"  F1 Score:  {test_metrics['f1']:.4f}")
    print(f"  FPR:       {test_metrics['fpr']:.4f} {'✅ ZERO' if test_metrics['fpr'] == 0 else '❌ NOT ZERO'}")
    print(f"  FNR:       {test_metrics['fnr']:.4f}")
    print(f"  TP: {test_metrics['tp']}  FP: {test_metrics['fp']}  FN: {test_metrics['fn']}  TN: {test_metrics['tn']}")

    # Also evaluate zero-FPR model if available
    if zero_fpr_model_state is not None:
        model.load_state_dict(zero_fpr_model_state)
        model = model.to(device)
        zero_test_metrics = evaluate(model, test_loader, criterion, device)
        print(f"\n{'='*80}")
        print(f"Test Results (Zero FPR Model)")
        print(f"{'='*80}")
        print(f"  Loss:      {zero_test_metrics['loss']:.4f}")
        print(f"  Accuracy:  {zero_test_metrics['accuracy']:.4f}")
        print(f"  Precision: {zero_test_metrics['precision']:.4f}")
        print(f"  Recall:    {zero_test_metrics['recall']:.4f}")
        print(f"  F1 Score:  {zero_test_metrics['f1']:.4f}")
        print(f"  FPR:       {zero_test_metrics['fpr']:.4f} {'✅ ZERO' if zero_test_metrics['fpr'] == 0 else '❌ NOT ZERO'}")
        print(f"  FNR:       {zero_test_metrics['fnr']:.4f}")
        print(f"  TP: {zero_test_metrics['tp']}  FP: {zero_test_metrics['fp']}  FN: {zero_test_metrics['fn']}  TN: {zero_test_metrics['tn']}")

    # Save final model
    final_path = output_path / "final_model.pt"
    torch.save(model.cpu().state_dict(), final_path)
    print(f"\nFinal model saved to: {final_path}")

    # Save training report
    report = {
        "timestamp": datetime.now().isoformat(),
        "architecture": model.get_model_info(),
        "training_config": {
            "epochs": epochs,
            "batch_size": batch_size,
            "learning_rate": learning_rate,
            "optimizer": "AdamW",
            "scheduler": "CosineAnnealingLR",
            "loss": "FocalLoss(alpha=0.25, gamma=2.0)",
            "device": str(device),
        },
        "data": {
            "train_size": len(train_dataset),
            "val_size": len(val_dataset),
            "test_size": len(test_dataset),
        },
        "best_model": {
            "epoch": best_epoch,
            "val_f1": best_val_f1,
            "test_metrics": test_metrics,
        },
        "zero_fpr_model": {
            "test_metrics": zero_test_metrics if zero_fpr_model_state is not None else None,
        },
        "training_time_seconds": total_time,
    }

    report_path = output_path / "training_report.json"
    with open(report_path, 'w') as f:
        json.dump(report, f, indent=2, default=str)
    print(f"Training report saved to: {report_path}")

    return model, test_metrics, report


