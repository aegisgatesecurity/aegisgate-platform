def split_dataset(examples: list, train_ratio: float = 0.8, val_ratio: float = 0.1,
                  test_ratio: float = 0.1, seed: int = SEED):
    """Split examples into train/val/test sets matching Go SplitDataset."""
    rng = np.random.RandomState(seed)
    indices = list(range(len(examples)))
    rng.shuffle(indices)

    n = len(examples)
    train_end = int(n * train_ratio)
    val_end = train_end + int(n * val_ratio)

    train = [examples[i] for i in indices[:train_end]]
    val = [examples[i] for i in indices[train_end:val_end]]
    test = [examples[i] for i in indices[val_end:]]

    return train, val, test


