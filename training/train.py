def load_jsonl(path: str) -> list:
    """Load examples from a JSONL file."""
    examples = []
    with open(path, 'r') as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                ex = json.loads(line)
                if "text" in ex and "label" in ex:
                    examples.append(ex)
            except json.JSONDecodeError:
                continue
    return examples


