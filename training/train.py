class ThreatDataset(Dataset):
    """Dataset for threat detection training examples.
    
    Loads from JSONL files generated by pkg/ml/training/augment.go.
    Each line: {"text": "...", "label": "adversarial"|"benign", ...}
    """

    def __init__(self, examples: list, normalizer: CharNormalizer = None):
        self.examples = examples
        self.normalizer = normalizer or CharNormalizer()
        self.encoded_cache = []
        for ex in examples:
            encoded = self.normalizer.encode(ex["text"])
            label = LABEL_MAP[ex["label"]]
            self.encoded_cache.append((encoded, label))

    def __len__(self):
        return len(self.encoded_cache)

    def __getitem__(self, idx):
        encoded, label = self.encoded_cache[idx]
        return {
            "input_ids": torch.tensor(encoded, dtype=torch.int32),
            "label": torch.tensor(label, dtype=torch.float32),
        }


