    parser.add_argument("--lr", type=float, default=DEFAULT_LEARNING_RATE,
                        help=f"Learning rate (default: {DEFAULT_LEARNING_RATE})")
    parser.add_argument("--device", type=str, default="auto",
                        help="Device (auto, cpu, cuda)")
    parser.add_argument("--output-dir", type=str, default="training/checkpoints",
                        help="Output directory for checkpoints")
    parser.add_argument("--seed", type=int, default=SEED,
                        help=f"Random seed (default: {SEED})")
    args = parser.parse_args()

    # Set random seeds
    torch.manual_seed(args.seed)
    np.random.seed(args.seed)

    # Load data
    if args.synthetic:
        print("Using synthetic data for pipeline testing...")
        examples = generate_synthetic_data()
        train_data, val_data, test_data = split_dataset(
            examples, train_ratio=0.8, val_ratio=0.1, test_ratio=0.1
        )
    elif args.data_dir:
        data_dir = Path(args.data_dir)
        print(f"Loading data from {data_dir}...")
        
        # Try to load split files first
        train_path = data_dir / "train.jsonl"
        val_path = data_dir / "val.jsonl"
        test_path = data_dir / "test.jsonl"
        
        if train_path.exists() and val_path.exists() and test_path.exists():
            train_data = load_jsonl(str(train_path))
            val_data = load_jsonl(str(val_path))
            test_data = load_jsonl(str(test_path))
            print(f"Loaded split files: train={len(train_data)}, val={len(val_data)}, test={len(test_data)}")
        else:
            # Try loading combined file and splitting
            combined_path = data_dir / "combined.jsonl"
            if not combined_path.exists():
                # Try any JSONL file in the directory
                jsonl_files = list(data_dir.glob("*.jsonl"))
                if jsonl_files:
                    combined_path = jsonl_files[0]
                else:
                    print(f"No JSONL files found in {data_dir}")
                    print("Falling back to synthetic data...")
                    examples = generate_synthetic_data()
                    train_data, val_data, test_data = split_dataset(examples)
            else:
                examples = load_jsonl(str(combined_path))
                train_data, val_data, test_data = split_dataset(examples)
                print(f"Loaded combined file: {len(examples)} examples")
    else:
        # No data specified — try Go-generated data first, then synthetic
        go_data_path = Path("pkg/ml/training")
        jsonl_files = list(go_data_path.glob("*.jsonl")) if go_data_path.exists() else []
        
        if jsonl_files:
            print(f"Loading data from {go_data_path}...")
            all_examples = []
            for f in jsonl_files:
                all_examples.extend(load_jsonl(str(f)))
            train_data, val_data, test_data = split_dataset(all_examples)
            print(f"Loaded {len(all_examples)} examples from Go pipeline")
        else:
            print("No data files found. Using synthetic data for pipeline testing.")
            print("Run Go data pipeline first: go run pkg/ml/training/augment.go")
            examples = generate_synthetic_data()
            train_data, val_data, test_data = split_dataset(examples)

    # Validate labels
    for split_name, split_data in [("train", train_data), ("val", val_data), ("test", test_data)]:
        labels = set(ex.get("label", "") for ex in split_data)
        if not labels.issubset({"benign", "adversarial"}):
            print(f"WARNING: Unexpected labels in {split_name}: {labels}")
        adv_count = sum(1 for ex in split_data if ex.get("label") == "adversarial")
        ben_count = sum(1 for ex in split_data if ex.get("label") == "benign")
        print(f"  {split_name}: {len(split_data)} examples ({adv_count} adversarial, {ben_count} benign)")

    # Create datasets
    train_dataset = ThreatDataset(train_data)
    val_dataset = ThreatDataset(val_data)
    test_dataset = ThreatDataset(test_data)

    # Create model
    model = create_model()

    # Train
    model, test_metrics, report = train_model(
        model=model,
        train_dataset=train_dataset,
        val_dataset=val_dataset,
        test_dataset=test_dataset,
        epochs=args.epochs,
        batch_size=args.batch_size,
        learning_rate=args.lr,
        device=args.device,
        output_dir=args.output_dir,
    )

    # Print final assessment
    print(f"\n{'='*80}")
    print(f"FINAL ASSESSMENT")
    print(f"{'='*80}")
    
    fpr_ok = test_metrics['fpr'] == 0
    recall_ok = test_metrics['recall'] >= 0.95
    
    if fpr_ok and recall_ok:
        print(f"✅ MODEL PASSES ALL REQUIREMENTS")
        print(f"   FPR: {test_metrics['fpr']:.4f} (target: 0.00) {'✅' if fpr_ok else '❌'}")
        print(f"   Recall: {test_metrics['recall']:.4f} (target: ≥0.95) {'✅' if recall_ok else '❌'}")
    else:
        print(f"⚠️  MODEL DOES NOT MEET ALL REQUIREMENTS")
        print(f"   FPR: {test_metrics['fpr']:.4f} (target: 0.00) {'✅' if fpr_ok else '❌'}")
        print(f"   Recall: {test_metrics['recall']:.4f} (target: ≥0.95) {'✅' if recall_ok else '❌'}")
        print(f"   Consider: more epochs, data augmentation, or threshold tuning")


