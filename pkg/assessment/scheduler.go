// AegisGate Platform — Posture Assessment Module
// Phase 3: Scheduled Assessments with Alerting
//
// scheduler.go runs posture assessments on a configurable schedule and
// triggers alerts when:
//
//   - The score drops below a configurable threshold
//   - New gaps appear that weren't in the previous assessment
//   - The score regresses (drops compared to the previous run)
//
// Alert delivery is pluggable via the AlertHandler interface. Built-in
// handlers:
//   - LogAlertHandler: writes alerts to the standard logger
//   - ChannelAlertHandler: sends alerts to a Go channel (for in-app UI)
//   - WebhookAlertHandler: POSTs alerts to an HTTP endpoint (for Slack/Discord/etc.)
//
// The scheduler uses a ticker and runs in a goroutine. It is safe for
// concurrent use and can be stopped gracefully via Stop().

package assessment

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"log"
	"net/http"
	"sync"
	"time"
)

// =========================================================================
// Alert Types
// =========================================================================

// AlertType classifies the type of posture alert.
type AlertType string

const (
	AlertScoreDrop       AlertType = "score_drop"       // Score fell below threshold
	AlertScoreRegression AlertType = "score_regression" // Score dropped vs previous run
	AlertNewGaps         AlertType = "new_gaps"         // New gaps appeared
	AlertAssessmentDone  AlertType = "assessment_done"  // Assessment completed (info)
)

// AlertSeverity classifies alert urgency.
type AlertSeverity string

const (
	AlertCritical AlertSeverity = "critical"
	AlertHigh     AlertSeverity = "high"
	AlertMedium   AlertSeverity = "medium"
	AlertLow      AlertSeverity = "low"
)

// PostureAlert is an alert generated by the scheduler.
type PostureAlert struct {
	Type          AlertType     `json:"type"`
	Severity      AlertSeverity `json:"severity"`
	AssessmentID  string        `json:"assessment_id"`
	Score         float64       `json:"score"`
	PreviousScore float64       `json:"previous_score"`
	NewGaps       []string      `json:"new_gaps,omitempty"`
	Message       string        `json:"message"`
	Timestamp     time.Time     `json:"timestamp"`
}

// AlertHandler is the interface for alert delivery.
type AlertHandler interface {
	Deliver(alert PostureAlert) error
}

// =========================================================================
// Built-in Alert Handlers
// =========================================================================

// LogAlertHandler writes alerts to the standard logger.
type LogAlertHandler struct{}

func (h *LogAlertHandler) Deliver(alert PostureAlert) error {
	log.Printf("[POSTURE ALERT] [%s] [%s] %s (score: %.1f%%, prev: %.1f%%)",
		alert.Severity, alert.Type, alert.Message, alert.Score*100, alert.PreviousScore*100)
	return nil
}

// ChannelAlertHandler sends alerts to a Go channel.
// Useful for in-app notifications and UI updates.
type ChannelAlertHandler struct {
	ch chan PostureAlert
}

// NewChannelAlertHandler creates a handler that sends alerts to the given channel.
// The channel should have a buffer large enough to avoid blocking.
func NewChannelAlertHandler(ch chan PostureAlert) *ChannelAlertHandler {
	return &ChannelAlertHandler{ch: ch}
}

func (h *ChannelAlertHandler) Deliver(alert PostureAlert) error {
	select {
	case h.ch <- alert:
		return nil
	default:
		return fmt.Errorf("alert channel full — dropping alert")
	}
}

// WebhookAlertHandler POSTs alerts as JSON to an HTTP endpoint.
// Useful for Slack, Discord, Microsoft Teams, or custom integrations.
type WebhookAlertHandler struct {
	URL     string
	Timeout time.Duration
}

func (h *WebhookAlertHandler) Deliver(alert PostureAlert) error {
	if h.URL == "" {
		return fmt.Errorf("webhook URL is empty")
	}
	timeout := h.Timeout
	if timeout == 0 {
		timeout = 10 * time.Second
	}

	payload, err := json.Marshal(alert)
	if err != nil {
		return fmt.Errorf("marshal alert: %w", err)
	}

	client := &http.Client{Timeout: timeout}
	resp, err := client.Post(h.URL, "application/json", bytes.NewReader(payload))
	if err != nil {
		return fmt.Errorf("webhook POST: %w", err)
	}
	defer resp.Body.Close()

	if resp.StatusCode >= 400 {
		return fmt.Errorf("webhook returned %d", resp.StatusCode)
	}
	return nil
}

// MultiAlertHandler delivers alerts to multiple handlers.
// If one handler fails, the remaining handlers are still called.
type MultiAlertHandler struct {
	handlers []AlertHandler
}

// NewMultiAlertHandler creates a handler that fans out to multiple handlers.
func NewMultiAlertHandler(handlers ...AlertHandler) *MultiAlertHandler {
	return &MultiAlertHandler{handlers: handlers}
}

func (h *MultiAlertHandler) Deliver(alert PostureAlert) error {
	var lastErr error
	for _, handler := range h.handlers {
		if err := handler.Deliver(alert); err != nil {
			lastErr = err
		}
	}
	return lastErr
}

// =========================================================================
// Scheduler Configuration
// =========================================================================

// SchedulerConfig configures the posture assessment scheduler.
type SchedulerConfig struct {
	// Interval is the time between assessment runs. Default: 24h.
	Interval time.Duration

	// MinScore is the minimum acceptable score. If the assessment
	// score falls below this, a score_drop alert is generated.
	// Default: 0.80 (80%).
	MinScore float64

	// AlertOnRegression generates an alert if the score drops compared
	// to the previous run. Default: true.
	AlertOnRegression bool

	// AlertOnNewGaps generates an alert if new gaps appear that weren't
	// in the previous assessment. Default: true.
	AlertOnNewGaps bool

	// AlertOnComplete generates an info-level alert when each assessment
	// completes (regardless of score). Default: false.
	AlertOnComplete bool

	// RunnerConfig is the config for the assessment runner.
	// If nil, DefaultRunnerConfig() is used.
	RunnerConfig *RunnerConfig

	// AlertHandler is the handler for delivering alerts.
	// If nil, alerts are logged via the standard logger.
	AlertHandler AlertHandler
}

// DefaultSchedulerConfig returns the default scheduler configuration.
func DefaultSchedulerConfig() SchedulerConfig {
	return SchedulerConfig{
		Interval:          24 * time.Hour,
		MinScore:          0.80,
		AlertOnRegression: true,
		AlertOnNewGaps:    true,
		AlertOnComplete:   false,
		RunnerConfig:      DefaultRunnerConfig(),
		AlertHandler:      &LogAlertHandler{},
	}
}

// =========================================================================
// Scheduler
// =========================================================================

// Scheduler runs posture assessments on a schedule and triggers alerts.
type Scheduler struct {
	cfg            SchedulerConfig
	mu             sync.Mutex
	previousResult *AssessmentResult
	cancel         context.CancelFunc
	running        bool
	runCount       int
}

// NewScheduler creates a new posture assessment scheduler.
func NewScheduler(cfg SchedulerConfig) *Scheduler {
	if cfg.Interval <= 0 {
		cfg.Interval = 24 * time.Hour
	}
	if cfg.MinScore <= 0 {
		cfg.MinScore = 0.80
	}
	if cfg.RunnerConfig == nil {
		cfg.RunnerConfig = DefaultRunnerConfig()
	}
	if cfg.AlertHandler == nil {
		cfg.AlertHandler = &LogAlertHandler{}
	}
	return &Scheduler{cfg: cfg}
}

// Start begins the scheduler in a background goroutine. The scheduler
// runs an assessment immediately, then repeats at the configured interval.
// Call Stop() to shut down gracefully.
func (s *Scheduler) Start() error {
	s.mu.Lock()
	if s.running {
		s.mu.Unlock()
		return fmt.Errorf("scheduler is already running")
	}
	s.mu.Unlock()

	ctx, cancel := context.WithCancel(context.Background())
	s.mu.Lock()
	s.cancel = cancel
	s.running = true
	s.mu.Unlock()

	go s.runLoop(ctx)
	return nil
}

// Stop shuts down the scheduler gracefully. It waits for any in-progress
// assessment to complete before returning.
func (s *Scheduler) Stop() {
	s.mu.Lock()
	if s.cancel != nil {
		s.cancel()
	}
	s.running = false
	s.mu.Unlock()
}

// IsRunning returns whether the scheduler is currently running.
func (s *Scheduler) IsRunning() bool {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.running
}

// RunCount returns the number of assessments that have been run.
func (s *Scheduler) RunCount() int {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.runCount
}

// PreviousResult returns the most recent assessment result, or nil if
// no assessment has been run yet.
func (s *Scheduler) PreviousResult() *AssessmentResult {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.previousResult
}

// RunOnce runs a single assessment immediately (outside the scheduled
// interval) and processes alerts. This is useful for on-demand assessments
// and for testing.
func (s *Scheduler) RunOnce() (*AssessmentResult, error) {
	return s.runAssessment()
}

// runLoop is the main scheduler loop.
func (s *Scheduler) runLoop(ctx context.Context) {
	ticker := time.NewTicker(s.cfg.Interval)
	defer ticker.Stop()

	// Run immediately on start.
	s.runAssessment()

	for {
		select {
		case <-ctx.Done():
			return
		case <-ticker.C:
			s.runAssessment()
		}
	}
}

// runAssessment runs a single assessment and processes alerts.
func (s *Scheduler) runAssessment() (*AssessmentResult, error) {
	runner, err := NewRunner(s.cfg.RunnerConfig)
	if err != nil {
		return nil, fmt.Errorf("scheduler: create runner: %w", err)
	}

	// Close ML detector if present.
	if runner.mlDetector != nil {
		defer runner.mlDetector.Close()
	}

	result, err := runner.Run()
	if err != nil {
		return nil, fmt.Errorf("scheduler: run assessment: %w", err)
	}

	s.mu.Lock()
	s.runCount++
	prev := s.previousResult
	s.previousResult = result
	s.mu.Unlock()

	// Process alerts.
	s.processAlerts(result, prev)

	return result, nil
}

// processAlerts evaluates the assessment result and generates alerts.
func (s *Scheduler) processAlerts(result *AssessmentResult, prev *AssessmentResult) {
	now := time.Now().UTC()

	// Info: assessment complete.
	if s.cfg.AlertOnComplete {
		s.deliver(PostureAlert{
			Type:         AlertAssessmentDone,
			Severity:     AlertLow,
			AssessmentID: result.ID,
			Score:        result.Score,
			Message:      fmt.Sprintf("Assessment complete: %d/%d blocked (%.1f%%)", result.Blocked, result.Total, result.Score*100),
			Timestamp:    now,
		})
	}

	// Score below threshold.
	if result.Score < s.cfg.MinScore {
		s.deliver(PostureAlert{
			Type:         AlertScoreDrop,
			Severity:     AlertHigh,
			AssessmentID: result.ID,
			Score:        result.Score,
			Message:      fmt.Sprintf("Score %.1f%% is below minimum threshold %.1f%%", result.Score*100, s.cfg.MinScore*100),
			Timestamp:    now,
		})
	}

	if prev != nil {
		// Score regression.
		if s.cfg.AlertOnRegression && result.Score < prev.Score {
			s.deliver(PostureAlert{
				Type:          AlertScoreRegression,
				Severity:      AlertHigh,
				AssessmentID:  result.ID,
				Score:         result.Score,
				PreviousScore: prev.Score,
				Message:       fmt.Sprintf("Score regressed from %.1f%% to %.1f%% (-%.1f%%)", prev.Score*100, result.Score*100, (prev.Score-result.Score)*100),
				Timestamp:     now,
			})
		}

		// New gaps.
		if s.cfg.AlertOnNewGaps {
			newGaps := findNewGaps(prev, result)
			if len(newGaps) > 0 {
				s.deliver(PostureAlert{
					Type:          AlertNewGaps,
					Severity:      AlertMedium,
					AssessmentID:  result.ID,
					Score:         result.Score,
					PreviousScore: prev.Score,
					NewGaps:       newGaps,
					Message:       fmt.Sprintf("%d new gap(s) detected: %v", len(newGaps), newGaps),
					Timestamp:     now,
				})
			}
		}
	}
}

// deliver sends an alert to the configured handler.
func (s *Scheduler) deliver(alert PostureAlert) {
	if s.cfg.AlertHandler != nil {
		if err := s.cfg.AlertHandler.Deliver(alert); err != nil {
			log.Printf("[POSTURE] alert delivery failed: %v", err)
		}
	}
}

// findNewGaps returns scenario IDs that were blocked in the previous
// assessment but are now missed.
func findNewGaps(prev, curr *AssessmentResult) []string {
	prevMissed := make(map[string]bool)
	for _, sr := range prev.ScenarioResults {
		if !sr.Blocked {
			prevMissed[sr.ScenarioID] = true
		}
	}

	var newGaps []string
	for _, sr := range curr.ScenarioResults {
		if !sr.Blocked && !prevMissed[sr.ScenarioID] {
			newGaps = append(newGaps, sr.ScenarioID)
		}
	}
	return newGaps
}
